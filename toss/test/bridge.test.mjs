// bridge.js 시험: 가짜 SDK로 묶은 묶음을 브라우저에서 열어 검수표 항목을 확인한다.
// node test/bridge.test.mjs  (playwright 필요)
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'dist-test');
fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
await build({ entryPoints: [path.join(here, '..', 'bridge.js')], bundle: true, format: 'iife', outfile: path.join(out, 'bridge.js'), alias: { '@apps-in-toss/web-framework': path.join(here, 'fake-sdk.js') } });
let html = fs.readFileSync(path.join(here, '..', 'dist', 'index.html'), 'utf8');
fs.writeFileSync(path.join(out, 'index.html'), html);
const { chromium } = await import(process.env.PLAYWRIGHT || '/opt/npm-tools/node_modules/playwright/index.mjs');
let pass = 0, fail = 0; const ok = (c, n) => { c ? pass++ : fail++; console.log((c ? 'PASS  ' : 'FAIL  ') + n); };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
await ctx.route('**/api/collect', (r) => r.fulfill({ status: 204 }));
const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
const url = 'file://' + path.join(out, 'index.html'); // 수집 서버 요청은 위에서 가로챔
await p.goto(url); await p.waitForFunction(() => !!window.__track, null, { timeout: 8000 });
ok(await p.evaluate(() => window.PLATFORM && window.PLATFORM.name === 'toss'), '토스 환경에서 PLATFORM 심김');
ok(await p.evaluate(() => getComputedStyle(document.getElementById('wrap')).paddingTop === '54px'), '안전 영역 위쪽 54px 만큼 띄움');
await p.evaluate(() => window.PLATFORM.store.set('cp-best', '777'));
await p.waitForTimeout(500);
ok(await p.evaluate(() => JSON.parse(JSON.parse(localStorage.getItem('__fake_native_storage__'))['jelly-panic-store'])['cp-tosskey'] === 'fakehash123'), '식별키 발급·네이티브 저장');
await p.reload(); await p.waitForFunction(() => !!window.__track, null, { timeout: 8000 });
ok(await p.evaluate(() => window.PLATFORM.store.get('cp-best') === '777'), '다시 열어도 기록 유지(네이티브 저장소)');
await p.click('#help'); await p.waitForTimeout(200);
await p.evaluate(() => window.__fakeBack());
ok(await p.evaluate(() => !document.getElementById('dex').classList.contains('show') && !window.__closed), '뒤로가기: 열린 도감부터 닫음');
await p.evaluate(() => window.__fakeBack());
ok(await p.evaluate(() => document.getElementById('exitask').classList.contains('show') && !window.__closed), '뒤로가기: 열린 창 없으면 종료 확인 창');
await p.evaluate(() => window.__fakeBack());
ok(await p.evaluate(() => !document.getElementById('exitask').classList.contains('show') && !window.__closed), '뒤로가기: 종료 확인 창도 뒤로가기로 닫힘(계속)');
await p.evaluate(() => document.getElementById('quit').click());
await p.click('#exitgo');
ok(await p.evaluate(() => window.__closed === 1), '종료하기 → 확인 창 「끝내기」 → 미니앱 닫기');
ok(await p.evaluate(() => (window.__logs || []).includes('jp_start')), '토스 행동 기록에 판 시작이 남음');
await p.evaluate(() => document.getElementById('share').click()); await p.waitForTimeout(300);
ok(await p.evaluate(() => { const m = (window.__shared || [])[0] || ''; return m.indexOf('젤리 패닉') === 0 && m.indexOf(encodeURIComponent('intoss://jelly-panic?src=share')) > 0; }), '공유: 토스 공유 시트에 결과 글 + 토스 주소');
ok(errs.length === 0, '오류 0 ' + JSON.stringify(errs.slice(0, 2)));
// 저장소가 늦게 답해도(2초) 지난 기록을 덮어쓰지 않고 합침
const slowOut = path.join(out, 'slow'); fs.mkdirSync(slowOut, { recursive: true });
fs.writeFileSync(path.join(here, '..', 'dist-test', 'slow-sdk.mjs'), fs.readFileSync(path.join(here, 'fake-sdk.js'), 'utf8').replace("getItem: async (k) => {", "getItem: async (k) => { await new Promise((r) => setTimeout(r, 2000));"));
await build({ entryPoints: [path.join(here, '..', 'bridge.js')], bundle: true, format: 'iife', outfile: path.join(slowOut, 'bridge.js'), alias: { '@apps-in-toss/web-framework': path.join(out, 'slow-sdk.mjs') } });
fs.writeFileSync(path.join(slowOut, 'index.html'), html);
const p2 = await ctx.newPage(); p2.on('pageerror', (e) => errs.push(String(e)));
await p2.goto('file://' + path.join(slowOut, 'index.html'));
await p2.evaluate(() => localStorage.setItem('__fake_native_storage__', JSON.stringify({ 'jelly-panic-store': JSON.stringify({ 'cp-best': '777', 'cp-stages': '12', 'cp-did': 'abcdefabcdef' }) })));
await p2.reload(); await p2.waitForFunction(() => !!window.__track, null, { timeout: 8000 }); await p2.waitForTimeout(2500);
const nat2 = await p2.evaluate(() => JSON.parse(JSON.parse(localStorage.getItem('__fake_native_storage__'))['jelly-panic-store']));
ok(nat2['cp-best'] === '777' && nat2['cp-stages'] === '12' && nat2['cp-did'] === 'abcdefabcdef' && nat2['cp-tosskey'] === 'fakehash123', '저장소가 늦게 답해도 지난 기록 유지 ' + JSON.stringify(nat2));
ok(errs.length === 0, '느린 저장소에서도 오류 0');
await b.close();
fs.rmSync(out, { recursive: true, force: true });
console.log('\n' + pass + ' passed, ' + fail + ' failed'); process.exit(fail ? 1 : 0);
